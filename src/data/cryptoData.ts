/**
 * Generates realistic candle series for a given coin base price and trend
 */
// 10. ZERO Math.random! Deterministic Fourier/sinusoidal harmonics based on index and basePrice
export function generateSyntheticCandles(
  basePrice: number,
  count: number = 70,
  trendFactor: number = 0.003
): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const intervalMs = 15 * 60 * 1000; // 15 mins

  let currentPrice = basePrice * (1 - count * trendFactor * 0.4);
  const volatility = basePrice * 0.012;

  for (let i = 0; i < count; i++) {
    const time = now - (count - 1 - i) * intervalMs;
    const dateObj = new Date(time);
    const formattedTime = `${dateObj.getHours().toString().padStart(2, '0')}:${dateObj
      .getMinutes()
      .toString()
      .padStart(2, '0')}`;

    // Deterministic trigonometric harmonic wave modulation (ZERO Math.random!)
    const progress = i / Math.max(1, count - 1);
    const harmonic1 = Math.sin(progress * Math.PI * 6);
    const harmonic2 = Math.cos(progress * Math.PI * 11) * 0.45;
    const harmonic3 = Math.sin(progress * Math.PI * 19) * 0.22;
    const waveFluctuation = (harmonic1 + harmonic2 + harmonic3) * (volatility * 0.6);
    const trendContribution = (trendFactor * basePrice * 0.6) * (1 + progress);
    const delta = waveFluctuation + trendContribution;

    const open = currentPrice;
    const close = Math.max(open * 0.75, open + delta);
    const highDelta = Math.abs(Math.sin((i + 1) * 2.3)) * volatility * 0.7;
    const lowDelta = Math.abs(Math.cos((i + 2) * 1.9)) * volatility * 0.7;
    const high = Math.max(open, close) + highDelta;
    const low = Math.min(open, close) - lowDelta;
    
    // Deterministic volume based on price displacement and cycle
    const priceRange = Math.max(0.001, high - low);
    const volumeMultiplier = 1500 + Math.abs(Math.sin(i * 0.8)) * 3200;
    const volume = Math.floor((priceRange / Math.max(0.001, open)) * basePrice * volumeMultiplier);

    candles.push({
      time,
      formattedTime,
      open: Number(open.toFixed(open > 10 ? 2 : 5)),
      high: Number(high.toFixed(high > 10 ? 2 : 5)),
      low: Number(low.toFixed(low > 10 ? 2 : 5)),
      close: Number(close.toFixed(close > 10 ? 2 : 5)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last candle close strictly matches basePrice
  const last = candles[candles.length - 1];
  last.close = basePrice;
  last.high = Math.max(last.high, basePrice);
  last.low = Math.min(last.low, basePrice);

  return enrichCandlesWithIndicators(candles);
}
